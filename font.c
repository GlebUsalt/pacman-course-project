static void defineGlyph(char ch, const char* spec) {
    Glyph* g = &glyphs[(unsigned char)ch];
    g->n = 0;
    while (*spec && g->n < MAX_SEGS) {
        for (int k = 0; k < 4; k++) {
            char* end;
            g->seg[g->n][k] = strtof(spec, &end);   //читаем очередное число из строки
            spec = end;
            if (*spec == ',') spec++;               //пропускаем запятую между числами
        }
        if (*spec == ';') spec++;                   //";" значит, что отрезок закончился
        g->n++;
    }
}

void initFont(void) {
    for (size_t i = 0; i < sizeof(glyphSpecs) / sizeof(glyphSpecs[0]); i++)
        defineGlyph(glyphSpecs[i].ch, glyphSpecs[i].spec);   //превращаем строки таблицы в числа
}

const Glyph* getGlyph(unsigned char ch) {
    if (ch >= 128 || glyphs[ch].n == 0) return NULL;          //такой буквы нет (например, пробела)
    return &glyphs[ch];
}
